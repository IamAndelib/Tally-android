#!/usr/bin/env python3
"""Build app/src/main/assets/js/currencies.js: every currency's English name and the countries using each today, from
Unicode CLDR (the currency picker's names and country search, for web views that carry few of their own).

Usage: for p in cldr-core cldr-localenames-full cldr-numbers-full; do npm pack $p@48.2.0; done
       for f in cldr-*.tgz; do mkdir -p "${f%.tgz}" && tar xzf "$f" -C "${f%.tgz}"; done
       python3 tools/gen_currencies.py . app/src/main/assets/js/currencies.js
Keep the version in the file's header and THIRD_PARTY_NOTICES.md in step with the packages used."""
import json, re, sys

CLDR, OUT = sys.argv[1], sys.argv[2]
VER = "48.2.0"


def load(pkg, path):
    with open("%s/%s-%s/package/%s" % (CLDR, pkg, VER, path), encoding="utf-8") as f:
        return json.load(f)


regions = load("cldr-core", "supplemental/currencyData.json")["supplemental"]["currencyData"]["region"]
terr = load("cldr-localenames-full", "main/en/territories.json")["main"]["en"]["localeDisplayNames"]["territories"]
names = load("cldr-numbers-full", "main/en/currencies.json")["main"]["en"]["numbers"]["currencies"]
LICENSE = open("%s/cldr-core-%s/package/LICENSE" % (CLDR, VER), encoding="utf-8").read().strip()

# the codes Android's web view (Chromium's ICU) lists: kept even once retired, so a picked currency stays in the list
CHROMIUM = """AED AFN ALL AMD ANG AOA ARS AUD AWG AZN BAM BBD BDT BGN BHD BIF BMD BND BOB BRL BSD BTN BWP BYN BZD CAD
CDF CHF CLP CNY COP CRC CUC CUP CVE CZK DJF DKK DOP DZD EGP ERN ETB EUR FJD FKP GBP GEL GHS GIP GMD GNF GTQ GYD HKD
HNL HRK HTG HUF IDR ILS INR IQD IRR ISK JMD JOD JPY KES KGS KHR KMF KPW KRW KWD KYD KZT LAK LBP LKR LRD LSL LYD MAD
MDL MGA MKD MMK MNT MOP MRU MUR MVR MWK MXN MYR MZN NAD NGN NIO NOK NPR NZD OMR PAB PEN PGK PHP PKR PLN PYG QAR RON
RSD RUB RWF SAR SBD SCR SDG SEK SGD SHP SLL SOS SRD SSP STN SVC SYP SZL THB TJS TMT TND TOP TRY TTD TWD TZS UAH UGX
USD UYU UZS VES VND VUV WST XAF XCD XDR XOF XPF XSU YER ZAR ZMW ZWL""".split()
# CLDR region codes that aren't countries
NOT_COUNTRIES = {"ZZ", "EU", "EZ", "UN", "QO", "XA", "XB"}
# names people type that CLDR doesn't give
MORE_NAMES = {"MO": ["Macau"], "VA": ["Holy See"]}
# CLDR's English names, as the rest of the list writes them
NAME_FIX = {"XCG": "Caribbean Guilder"}

countries = {}
for r, history in sorted(regions.items()):
    if not re.fullmatch(r"[A-Z]{2}", r) or r in NOT_COUNTRIES or r not in terr:
        continue
    # in use today: no end date, and legal tender
    now = []
    for entry in history:
        for code, info in entry.items():
            if "_to" not in info and info.get("_tender") != "false" and code not in now:
                now.append(code)
    if not now:
        continue
    n = [terr[r]] + [terr[k] for k in (r + "-alt-short", r + "-alt-variant") if k in terr] + MORE_NAMES.get(r, [])
    n += [x.replace("St. ", "Saint ") for x in n if "St. " in x]  # "St. Lucia" is typed "Saint Lucia" too
    countries[r] = ("|".join(dict.fromkeys(n)), " ".join(now))

codes = sorted(set(CHROMIUM) | {c for _, cs in countries.values() for c in cs.split()})
missing = [c for c in codes if c not in names]
if missing:
    sys.exit("no English name for " + " ".join(missing))

q = lambda s: json.dumps(s, ensure_ascii=False)
with open(OUT, "w", encoding="utf-8") as f:
    f.write(
        """/*
 * currencies.js — Every currency Tally offers and the countries that use each today, with English names (Unicode CLDR
 * %s, generated by tools/gen_currencies.py). Android's web view carries names for only some 60 currencies and may list
 * fewer, so Tally keeps its own: the currency picker shows a name for every code and finds it by name, code, sign or
 * country (curMatch, layers.js). The data is Unicode's, under the Unicode License v3 (its notice ends this file;
 * LICENSES/Unicode-3.0.txt).
 */
"use strict";

/* code → English name */
const CUR_EN = {
"""
        % VER.split(".")[0]
    )
    for c in codes:
        f.write("  %s: %s,\n" % (c, q(NAME_FIX.get(c, names[c]["displayName"]))))
    f.write(
        """};
/* country (ISO 3166) → [its English names, "|" between them; the currencies it uses, main one first] */
const REGIONS = {
"""
    )
    for r, (n, cs) in countries.items():
        f.write("  %s: [%s, %s],\n" % (r, q(n), q(cs)))
    f.write("};\n\n/*\n" + "\n".join((" * " + l).rstrip() for l in LICENSE.split("\n")) + "\n */\n")
print("%d currencies, %d countries" % (len(codes), len(countries)))
