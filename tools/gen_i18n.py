#!/usr/bin/env python3
"""Build app/src/main/assets/js/i18n/<code>.js from the catalogues in l10n/web/<code>.json (i18next JSON v4, nested
by area), so the page can load them as scripts (its CSP allows no fetch). Each file holds the catalogue as one JSON
string with dotted keys, parsed by js/i18n.js only for the active language and English.

Usage: python3 tools/gen_i18n.py            write the files
       python3 tools/gen_i18n.py --check    exit 1 if any is missing, stale or left over"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "l10n", "web")
OUT = os.path.join(ROOT, "app", "src", "main", "assets", "js", "i18n")


def flat(o, pre=""):
    for k, v in o.items():
        if isinstance(v, dict):
            yield from flat(v, pre + k + ".")
        elif isinstance(v, str):
            yield pre + k, v
        else:
            sys.exit("%s%s: a text must be a string" % (pre, k))


def build(code):
    with open(os.path.join(SRC, code + ".json"), encoding="utf-8") as f:
        cat = dict(flat(json.load(f)))
    s = json.dumps(json.dumps(cat, ensure_ascii=False, separators=(",", ":")), ensure_ascii=False)
    s = s.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return (
        "/* generated by tools/gen_i18n.py from l10n/web/%s.json: edit that file, not this one */\n"
        '"use strict";\n'
        "(window.I18N = window.I18N || {})[%s] = %s;\n" % (code, json.dumps(code), s)
    )


want = {c[:-5] + ".js": build(c[:-5]) for c in sorted(os.listdir(SRC)) if c.endswith(".json")}
have = set(os.listdir(OUT)) if os.path.isdir(OUT) else set()
if "--check" in sys.argv:
    bad = [f for f, s in want.items() if f not in have or open(os.path.join(OUT, f), encoding="utf-8").read() != s]
    bad += sorted(have - set(want))
    if bad:
        sys.exit("stale: %s (run python3 tools/gen_i18n.py)" % " ".join(bad))
    print("%d catalogues up to date" % len(want))
else:
    os.makedirs(OUT, exist_ok=True)
    for f in have - set(want):
        os.remove(os.path.join(OUT, f))
    for f, s in want.items():
        with open(os.path.join(OUT, f), "w", encoding="utf-8", newline="\n") as o:
            o.write(s)
    print("%d catalogues" % len(want))
